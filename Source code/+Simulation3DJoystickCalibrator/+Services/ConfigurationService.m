classdef ConfigurationService
    %CONFIGURATIONSERVICE Create and validate shared joystick configurations.
    %
    % Copyright 2026 The MathWorks, Inc.
    %
    % A saved calibration describes only the physical four-axis controller:
    % Roll, Pitch, Yaw, and Throttle. Vehicle-specific output names and
    % limits are supplied by the consuming Simulink block.

    properties (Constant)
        MaxChannels = 64
    end

    methods (Static)
        function cfg = default(profileID, numAxes)
            arguments
                profileID {mustBeTextScalar} = "simulation-3d-joystick"
                numAxes (1,1) double {mustBeInteger, mustBePositive} = 4
            end

            requestedID = lower(strtrim(string(profileID)));
            if requestedID ~= ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID
                error('Simulation3DJoystickCalibrator:UnknownProfile', ...
                    ['Configuration profileID must be ' ...
                     '"simulation-3d-joystick"; received "%s".'], ...
                    requestedID);
            end
            if numAxes > ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.MaxChannels
                error('Simulation3DJoystickCalibrator:TooManyAxes', ...
                    'At most %d input axes are supported; requested %d.', ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.MaxChannels, ...
                    numAxes);
            end

            profile = ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.calibration();

            template = struct( ...
                'id', '', ...
                'label', '', ...
                'outputName', '', ...
                'channel', 1, ...
                'rawMin', -1, ...
                'rawMax', 1, ...
                'neutral', 0, ...
                'deadband', 0.02, ...
                'reverse', false, ...
                'mapping', 'centered', ...
                'outputMin', -1, ...
                'outputMax', 1, ...
                'unit', 'normalized');
            signals = repmat(template, 1, numel(profile.signals));
            for index = 1:numel(profile.signals)
                definition = profile.signals(index);
                signals(index) = struct( ...
                    'id', definition.id, ...
                    'label', definition.label, ...
                    'outputName', definition.outputName, ...
                    'channel', index, ...
                    'rawMin', definition.defaultRawMin, ...
                    'rawMax', definition.defaultRawMax, ...
                    'neutral', definition.defaultNeutral, ...
                    'deadband', definition.defaultDeadband, ...
                    'reverse', logical(definition.defaultReverse), ...
                    'mapping', definition.mapping, ...
                    'outputMin', definition.outputMin, ...
                    'outputMax', definition.outputMax, ...
                    'unit', definition.unit);
            end

            cfg = struct( ...
                'schemaVersion', ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.SchemaVersion, ...
                'profileID', ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID, ...
                'profileVersion', profile.profileVersion, ...
                'numAxes', max(numAxes, numel(signals)), ...
                'signals', signals, ...
                'savedAt', ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.timestamp(), ...
                'appVersion', ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.AppVersion);
        end

        function [cfg, report] = normalize(candidate)
            arguments
                candidate
            end

            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.newReport();
            cfg = struct();
            if ~(isstruct(candidate) && isscalar(candidate))
                report.problems = {'Configuration must be a scalar struct.'};
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end

            if ~isfield(candidate, 'schemaVersion')
                report.problems = { ...
                    'Missing schemaVersion. Only shared schema version 2 files are supported.'};
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end
            [cfg, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService. ...
                normalizeVersioned(candidate);
        end

        function [cfg, report] = load(filePath)
            arguments
                filePath {mustBeTextScalar}
            end

            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.newReport();
            cfg = struct();
            filePath = char(string(filePath));
            if ~isfile(filePath)
                report.problems = {sprintf('File not found: %s', filePath)};
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end

            try
                loaded = load(filePath);
            catch exception
                report.problems = {sprintf( ...
                    'Could not read .mat file: %s', exception.message)};
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end

            if isfield(loaded, 'cfg') && isstruct(loaded.cfg)
                candidate = loaded.cfg;
            else
                names = fieldnames(loaded);
                if isscalar(names) && isstruct(loaded.(names{1}))
                    candidate = loaded.(names{1});
                else
                    candidate = loaded;
                end
            end
            [cfg, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.normalize(candidate);
        end

        function cfg = save(cfg, filePath)
            arguments
                cfg (1,1) struct
                filePath {mustBeTextScalar}
            end

            [cfg, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.normalize(cfg);
            if ~report.ok
                error('Simulation3DJoystickCalibrator:InvalidConfiguration', ...
                    'Cannot save invalid calibration:%s%s', newline, ...
                    strjoin(report.problems, newline));
            end

            cfg.savedAt = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.timestamp();
            cfg.appVersion = ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.AppVersion;
            filePath = char(string(filePath));
            folder = fileparts(filePath);
            if ~isempty(folder) && ~isfolder(folder)
                mkdir(folder);
            end
            save(filePath, 'cfg');
        end

        function [ok, report] = validate(cfg)
            arguments
                cfg (1,1) struct
            end
            [~, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.normalize(cfg);
            ok = report.ok;
        end

        function vars = toRuntimeVariables(cfg, outputProfileID)
            arguments
                cfg (1,1) struct
                outputProfileID {mustBeTextScalar} = "fixed-wing"
            end

            [cfg, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.normalize(cfg);
            if ~report.ok
                error('Simulation3DJoystickCalibrator:InvalidConfiguration', ...
                    '%s', strjoin(report.problems, newline));
            end

            outputProfileID = ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.normalizeID( ...
                outputProfileID);
            if strcmp(outputProfileID, ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID)
                outputProfile = ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.calibration();
            else
                outputProfile = ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.get( ...
                    outputProfileID);
            end

            slots = {'Roll', 'Pitch', 'Yaw', 'Throttle'};
            outputSlots = {'aileron', 'elevator', 'rudder', 'throttle'};
            vars = struct( ...
                'profileID', outputProfile.id, ...
                'calibrationProfileID', cfg.profileID, ...
                'schemaVersion', cfg.schemaVersion, ...
                'numAxes', cfg.numAxes);
            for index = 1:4
                signal = cfg.signals(index);
                outputDefinition = outputProfile.signals(index);
                slot = slots{index};
                prefix = lower(slot);
                vars.([prefix 'Ch']) = signal.channel;
                vars.([prefix 'DB']) = signal.deadband;
                vars.(['u' slot 'Min']) = signal.rawMin;
                vars.(['u' slot 'Max']) = signal.rawMax;
                vars.([prefix 'Neutral']) = signal.neutral;
                vars.(['dir' slot]) = double(signal.reverse);
                outputPrefix = outputSlots{index};
                if strcmp(outputProfile.id, 'fixed-wing')
                    vars.([outputPrefix 'Min']) = signal.outputMin;
                    vars.([outputPrefix 'Max']) = signal.outputMax;
                else
                    vars.([outputPrefix 'Min']) = outputDefinition.outputMin;
                    vars.([outputPrefix 'Max']) = outputDefinition.outputMax;
                end
            end
            vars.savedAt = cfg.savedAt;
        end

        function expected = expectedProfileForBlock(blockName)
            arguments
                blockName {mustBeTextScalar}
            end

            name = lower(string(blockName));
            if contains(name, "multirotor")
                expected = 'multirotor';
            elseif contains(name, "helicopter")
                expected = 'helicopter';
            else
                expected = 'fixed-wing';
            end
        end

        function [tf, message] = isCompatible(cfg, expectedProfile)
            arguments
                cfg (1,1) struct
                expectedProfile {mustBeTextScalar}
            end

            [~, report] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.normalize(cfg);
            if ~report.ok
                tf = false;
                message = strjoin(report.problems, newline);
                return;
            end

            expectedProfile = ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.normalizeID( ...
                expectedProfile);
            tf = any(strcmp( ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.ids(), ...
                expectedProfile));
            if tf
                message = '';
            else
                message = sprintf('Unsupported block profile "%s".', ...
                    expectedProfile);
            end
        end
    end

    methods (Static, Access = private)
        function [cfg, report] = normalizeVersioned(candidate)
            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.newReport();
            cfg = struct();

            [schemaVersion, problem] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.number( ...
                candidate, 'schemaVersion', NaN, 1, Inf, true, true);
            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.addProblem( ...
                report, problem);
            if isempty(problem) && schemaVersion ~= ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.SchemaVersion
                report.problems{end+1} = sprintf( ...
                    'Unsupported schemaVersion %g; this release supports version %d.', ...
                    schemaVersion, ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.SchemaVersion);
            end

            if ~isfield(candidate, 'profileID') || ...
                    ~(ischar(candidate.profileID) || ...
                    (isstring(candidate.profileID) && isscalar(candidate.profileID)))
                report.problems{end+1} = ...
                    'profileID must be a supported text scalar.';
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end
            sourceProfileID = lower(strtrim(string(candidate.profileID)));
            if sourceProfileID ~= ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID
                report.problems{end+1} = sprintf( ...
                    ['profileID must be "simulation-3d-joystick"; ' ...
                     'received "%s".'], ...
                    sourceProfileID);
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end

            [profileVersion, problem] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.number( ...
                candidate, 'profileVersion', NaN, 1, Inf, true, true);
            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.addProblem( ...
                report, problem);
            if isempty(problem) && profileVersion ~= ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.ProfileVersion
                report.problems{end+1} = sprintf( ...
                    'Profile "%s" requires profileVersion %d.', ...
                    sourceProfileID, ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.ProfileVersion);
            end

            if ~isfield(candidate, 'signals') || ...
                    ~isstruct(candidate.signals) || ...
                    numel(candidate.signals) ~= 4
                report.problems{end+1} = ...
                    'signals must be a four-element struct array.';
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end

            sourceSignals = candidate.signals(:).';
            canonicalIDs = strings(1, numel(sourceSignals));
            for index = 1:numel(sourceSignals)
                if ~isfield(sourceSignals(index), 'id') || ...
                        ~(ischar(sourceSignals(index).id) || ...
                        (isstring(sourceSignals(index).id) && ...
                        isscalar(sourceSignals(index).id)))
                    report.problems{end+1} = ...
                        'Every signal must contain a text scalar id.';
                    continue;
                end
                canonicalIDs(index) = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService. ...
                    canonicalSignalID(sourceSignals(index).id);
                if strlength(canonicalIDs(index)) == 0
                    report.problems{end+1} = sprintf( ...
                        'Unsupported signal id "%s".', ...
                        string(sourceSignals(index).id));
                end
            end
            if any(strlength(canonicalIDs) == 0)
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
                return;
            end
            if numel(unique(canonicalIDs)) ~= 4
                report.problems{end+1} = ...
                    'Signal IDs must map uniquely to Roll, Pitch, Yaw, and Throttle.';
            end

            cfg = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.default( ...
                "simulation-3d-joystick");
            targetIDs = string({cfg.signals.id});
            normalizedSignals = cfg.signals;
            for index = 1:4
                sourceIndex = find(canonicalIDs == targetIDs(index), 1);
                if isempty(sourceIndex)
                    report.problems{end+1} = sprintf( ...
                        'Required signal "%s" is missing.', targetIDs(index));
                    continue;
                end
                source = sourceSignals(sourceIndex);
                signal = normalizedSignals(index);

                [signal.channel, problem] = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.number( ...
                    source, 'channel', signal.channel, 1, ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.MaxChannels, ...
                    true, true);
                report = ...
                    Simulation3DJoystickCalibrator.Services.ConfigurationService.addProblem( ...
                    report, problem);

                numericFields = {'rawMin','rawMax','neutral','deadband', ...
                    'outputMin','outputMax'};
                limits = [-Inf Inf; -Inf Inf; -Inf Inf; 0 Inf; ...
                    -Inf Inf; -Inf Inf];
                for fieldIndex = 1:numel(numericFields)
                    fieldName = numericFields{fieldIndex};
                    [signal.(fieldName), problem] = ...
                        Simulation3DJoystickCalibrator.Services.ConfigurationService.number( ...
                        source, fieldName, signal.(fieldName), ...
                        limits(fieldIndex,1), limits(fieldIndex,2), ...
                        false, true);
                    report = ...
                        Simulation3DJoystickCalibrator.Services.ConfigurationService.addProblem( ...
                        report, problem);
                end

                if isfield(source, 'reverse') && ...
                        (islogical(source.reverse) || isnumeric(source.reverse)) && ...
                        isscalar(source.reverse) && ...
                        isfinite(double(source.reverse)) && ...
                        ismember(double(source.reverse), [0 1])
                    signal.reverse = logical(source.reverse);
                else
                    report.problems{end+1} = sprintf( ...
                        'Signal "%s" field reverse must be scalar true or false.', ...
                        signal.id);
                end

                if signal.rawMin >= signal.rawMax
                    report.problems{end+1} = sprintf( ...
                        'Signal "%s" requires rawMin < rawMax.', signal.id);
                end
                if signal.neutral < signal.rawMin || ...
                        signal.neutral > signal.rawMax
                    report.problems{end+1} = sprintf( ...
                        'Signal "%s" neutral must lie within its raw range.', ...
                        signal.id);
                end
                if signal.deadband >= signal.rawMax - signal.rawMin
                    report.problems{end+1} = sprintf( ...
                        'Signal "%s" deadband must be smaller than its raw span.', ...
                        signal.id);
                end
                if signal.outputMin >= signal.outputMax
                    report.problems{end+1} = sprintf( ...
                        'Signal "%s" requires outputMin < outputMax.', ...
                        signal.id);
                end
                if strcmp(signal.mapping, 'centered') && ...
                        (signal.outputMin > 0 || signal.outputMax < 0)
                    report.problems{end+1} = sprintf( ...
                        ['Signal "%s" uses centered mapping, so its output range ' ...
                         'must include zero.'], signal.id);
                end
                normalizedSignals(index) = signal;
            end
            cfg.signals = normalizedSignals;

            [cfg.numAxes, problem] = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.number( ...
                candidate, 'numAxes', max([normalizedSignals.channel]), ...
                1, Simulation3DJoystickCalibrator.Services.ConfigurationService.MaxChannels, ...
                true, true);
            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.addProblem( ...
                report, problem);
            if cfg.numAxes < max([normalizedSignals.channel])
                report.problems{end+1} = sprintf( ...
                    'numAxes=%d does not cover the highest assigned channel (%d).', ...
                    cfg.numAxes, max([normalizedSignals.channel]));
            end
            if numel(unique([normalizedSignals.channel])) ~= 4
                report.problems{end+1} = ...
                    'Every required signal must use a unique channel.';
            end

            if isfield(candidate, 'savedAt') && ...
                    (ischar(candidate.savedAt) || ...
                    (isstring(candidate.savedAt) && isscalar(candidate.savedAt)))
                cfg.savedAt = char(string(candidate.savedAt));
            else
                report.warnings{end+1} = ...
                    'savedAt was missing or invalid; generated a new timestamp.';
            end
            if isfield(candidate, 'appVersion') && ...
                    (ischar(candidate.appVersion) || ...
                    (isstring(candidate.appVersion) && isscalar(candidate.appVersion)))
                cfg.appVersion = char(string(candidate.appVersion));
            else
                report.warnings{end+1} = ...
                    'appVersion was missing or invalid; using the current version.';
            end
            if isfield(candidate, 'joystickID')
                report.warnings{end+1} = ...
                    'joystickID is runtime state and was ignored.';
            end
            report = ...
                Simulation3DJoystickCalibrator.Services.ConfigurationService.finishReport(report);
        end

        function id = canonicalSignalID(value)
            value = lower(strtrim(string(value)));
            switch value
                case "roll"
                    id = "roll";
                case "pitch"
                    id = "pitch";
                case "yaw"
                    id = "yaw";
                case "throttle"
                    id = "throttle";
                otherwise
                    id = "";
            end
        end

        function [value, problem] = number(source, name, defaultValue, ...
                lowerLimit, upperLimit, integerOnly, required)
            value = defaultValue;
            problem = '';
            if ~isfield(source, name)
                if required
                    problem = sprintf('Missing required field %s.', name);
                end
                return;
            end
            candidate = source.(name);
            if ~(isnumeric(candidate) || islogical(candidate)) || ...
                    ~isscalar(candidate) || ~isfinite(double(candidate))
                problem = sprintf('%s must be a finite numeric scalar.', name);
                return;
            end
            candidate = double(candidate);
            if integerOnly && candidate ~= round(candidate)
                problem = sprintf('%s must be a whole number.', name);
                return;
            end
            if candidate < lowerLimit || candidate > upperLimit
                problem = sprintf('%s=%g is outside [%g, %g].', ...
                    name, candidate, lowerLimit, upperLimit);
                return;
            end
            value = candidate;
        end

        function report = addProblem(report, problem)
            if ~isempty(problem)
                report.problems{end+1} = problem;
            end
        end

        function report = newReport()
            report = struct( ...
                'ok', false, ...
                'problems', {{}}, ...
                'warnings', {{}}, ...
                'summary', '');
        end

        function report = finishReport(report)
            report.ok = isempty(report.problems);
            if report.ok
                report.summary = sprintf( ...
                    'Valid shared schema v2 calibration (%d warning(s)).', ...
                    numel(report.warnings));
            else
                report.summary = sprintf( ...
                    '%d problem(s) found; configuration was not accepted.', ...
                    numel(report.problems));
            end
        end

        function value = timestamp()
            value = char(datetime('now', 'TimeZone', 'UTC', ...
                'Format', "yyyy-MM-dd'T'HH:mm:ss'Z'"));
        end
    end
end
