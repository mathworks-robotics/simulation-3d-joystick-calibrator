classdef ProfileCatalog
    %PROFILECATALOG Definitions for the profiles shipped with the toolbox.
    %
    % Copyright 2026 The MathWorks, Inc.

    properties (Constant)
        SchemaVersion = 2
        ProfileVersion = 1
        AppVersion = '1.0'
        CalibrationProfileID = 'simulation-3d-joystick'
    end

    methods (Static)
        function ids = ids()
            ids = ["fixed-wing", "multirotor", "helicopter"];
        end

        function names = displayNames()
            profiles = Simulation3DJoystickCalibrator.Services.ProfileCatalog.all();
            names = string({profiles.displayName});
        end

        function profiles = all()
            profiles = [ ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.fixedWing(), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.multirotor(), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.helicopter()];
        end

        function profile = get(profileID)
            arguments
                profileID {mustBeTextScalar}
            end

            profileID = Simulation3DJoystickCalibrator.Services.ProfileCatalog.normalizeID(profileID);
            if strcmp(profileID, ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID)
                profile = ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.calibration();
                return;
            end
            profiles = Simulation3DJoystickCalibrator.Services.ProfileCatalog.all();
            index = find(strcmp({profiles.id}, profileID), 1);
            if isempty(index)
                error('Simulation3DJoystickCalibrator:UnknownProfile', ...
                    'Unsupported input profile "%s". Supported profiles are: %s.', ...
                    profileID, strjoin(Simulation3DJoystickCalibrator.Services.ProfileCatalog.ids(), ', '));
            end
            profile = profiles(index);
        end

        function profileID = normalizeID(profileID)
            arguments
                profileID {mustBeTextScalar}
            end

            value = lower(strtrim(string(profileID)));
            value = replace(value, ["_", " "], "-");
            switch value
                case {"simulation-3d-joystick", "simulation3djoystick", ...
                        "simulation-3d-joystick-calibration", "joystick", ...
                        "generic", "all"}
                    profileID = ...
                        Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID;
                case {"fixedwing", "fixed-wing", "airplane", "aeroplane"}
                    profileID = 'fixed-wing';
                case {"multirotor", "multi-rotor", "multicopter", "quadcopter"}
                    profileID = 'multirotor';
                case {"helicopter", "heli"}
                    profileID = 'helicopter';
                otherwise
                    profileID = char(value);
            end
        end

        function tf = isSupported(profileID)
            arguments
                profileID {mustBeTextScalar}
            end
            normalized = Simulation3DJoystickCalibrator.Services.ProfileCatalog.normalizeID(profileID);
            tf = strcmp(normalized, ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID) || ...
                any(strcmp(Simulation3DJoystickCalibrator.Services.ProfileCatalog.ids(), normalized));
        end

        function profile = calibration()
            signals = [ ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'roll', 'Roll', 'Roll', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'pitch', 'Pitch', 'Pitch', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'yaw', 'Yaw', 'Yaw', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'throttle', 'Throttle', 'Throttle', ...
                    'unipolar', [0 100], '%')];

            profile = Simulation3DJoystickCalibrator.Services.ProfileCatalog.profile( ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.CalibrationProfileID, ...
                'Simulation 3D Joystick', ...
                ['Vehicle-neutral Roll, Pitch, Yaw, and Throttle calibration. ' ...
                 'The consuming Simulink block owns output names and limits.'], ...
                '', signals);
        end
    end

    methods (Static, Access = private)
        function profile = fixedWing()
            signals = [ ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'roll', 'Roll', 'Aileron', 'centered', [-15 15], 'deg'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'pitch', 'Pitch', 'Elevator', 'centered', [-25 25], 'deg'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'yaw', 'Yaw', 'Rudder', 'centered', [-20 20], 'deg'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'throttle', 'Throttle', 'Throttle', 'unipolar', [0 100], '%')];

            profile = Simulation3DJoystickCalibrator.Services.ProfileCatalog.profile( ...
                'fixed-wing', 'Fixed Wing', ...
                ['Calibrates conventional roll, pitch, yaw, and throttle inputs ' ...
                 'for fixed-wing flight-control simulations.'], ...
                'Calibrated Fixed-Wing Input', signals);
        end

        function profile = multirotor()
            signals = [ ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'roll', 'Roll', 'RollCmd', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'pitch', 'Pitch', 'PitchCmd', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'yaw', 'Yaw', 'YawCmd', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'throttle', 'Throttle', 'ThrottleCmd', 'unipolar', [0 1], 'normalized')];

            profile = Simulation3DJoystickCalibrator.Services.ProfileCatalog.profile( ...
                'multirotor', 'Multirotor', ...
                ['Calibrates normalized attitude-rate/stick commands and a ' ...
                 'unipolar throttle command for multirotor simulations.'], ...
                'Calibrated Multirotor Input', signals);
        end

        function profile = helicopter()
            signals = [ ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'lateral-cyclic', 'Lateral Cyclic', 'LateralCyclic', ...
                    'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'longitudinal-cyclic', 'Longitudinal Cyclic', ...
                    'LongitudinalCyclic', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'pedals', 'Pedals', 'Pedals', 'centered', [-1 1], 'normalized'), ...
                Simulation3DJoystickCalibrator.Services.ProfileCatalog.signal( ...
                    'collective', 'Collective', 'Collective', ...
                    'unipolar', [0 1], 'normalized')];

            profile = Simulation3DJoystickCalibrator.Services.ProfileCatalog.profile( ...
                'helicopter', 'Helicopter', ...
                ['Calibrates cyclic, anti-torque pedal, and collective inputs ' ...
                 'for conventional helicopter simulations.'], ...
                'Calibrated Helicopter Input', signals);
        end

        function value = profile(id, displayName, description, blockName, signals)
            value = struct( ...
                'id', id, ...
                'displayName', displayName, ...
                'description', description, ...
                'compatibleBlock', blockName, ...
                'profileVersion', ...
                    Simulation3DJoystickCalibrator.Services.ProfileCatalog.ProfileVersion, ...
                'signals', signals);
        end

        function value = signal(id, label, outputName, mapping, outputLimits, unit)
            value = struct( ...
                'id', id, ...
                'label', label, ...
                'outputName', outputName, ...
                'mapping', mapping, ...
                'defaultChannel', 0, ...
                'defaultRawMin', -1, ...
                'defaultRawMax', 1, ...
                'defaultNeutral', 0, ...
                'defaultDeadband', 0.02, ...
                'defaultReverse', false, ...
                'outputMin', outputLimits(1), ...
                'outputMax', outputLimits(2), ...
                'unit', unit, ...
                'required', true);
        end
    end
end
